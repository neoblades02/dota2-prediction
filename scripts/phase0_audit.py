"""Phase 0 — source and feasibility audit.

Hits each planned provider endpoint once (politely), records HTTP status,
rate-limit headers, top-level field inventory, and saves raw sample payloads
under data/raw/audit/. Writes docs/phase0_audit.md from actual findings.

Run:  .venv/Scripts/python.exe scripts/phase0_audit.py
"""

from __future__ import annotations

import json
import sys
import time
from pathlib import Path

import httpx

ROOT = Path(__file__).resolve().parents[1]
AUDIT_DIR = ROOT / "data" / "raw" / "audit"
AUDIT_DIR.mkdir(parents=True, exist_ok=True)

OPENDOTA = "https://api.opendota.com/api"
HEADERS = {"User-Agent": "dota-predictor-phase0-audit/0.1 (research)"}

results: list[dict] = []


def probe(name: str, url: str, save_as: str | None = None, note: str = "") -> dict:
    rec: dict = {"endpoint": name, "url": url, "note": note}
    try:
        with httpx.Client(timeout=30.0, headers=HEADERS, follow_redirects=True) as c:
            r = c.get(url)
        rec["status"] = r.status_code
        rec["elapsed_s"] = round(r.elapsed.total_seconds(), 3)
        rl = {k: v for k, v in r.headers.items() if "rate" in k.lower() or "retry" in k.lower()}
        rec["rate_limit_headers"] = rl
        rec["content_type"] = r.headers.get("content-type", "")
        if r.status_code == 200:
            body = r.json() if "json" in rec["content_type"] or url.endswith("json") else r.text
            if save_as:
                (AUDIT_DIR / save_as).write_text(
                    json.dumps(body, indent=2, default=str) if not isinstance(body, str) else body,
                    encoding="utf-8",
                )
            if isinstance(body, list) and body:
                rec["n_items"] = len(body)
                rec["item_keys"] = sorted(body[0].keys()) if isinstance(body[0], dict) else type(body[0]).__name__
            elif isinstance(body, dict):
                rec["item_keys"] = sorted(body.keys())
            else:
                rec["body_preview"] = str(body)[:200]
        else:
            rec["body_preview"] = r.text[:200]
    except Exception as e:  # noqa: BLE001
        rec["error"] = f"{type(e).__name__}: {e}"
    results.append(rec)
    time.sleep(1.2)  # be polite between audit calls
    return rec


def main() -> int:
    # 1. Pro match index — first page
    p1 = probe("opendota /proMatches", f"{OPENDOTA}/proMatches", "proMatches_p1.json")

    # 2. Pagination — follow less_than_match_id cursor
    min_id = None
    try:
        page = json.loads((AUDIT_DIR / "proMatches_p1.json").read_text())
        min_id = min(m["match_id"] for m in page)
    except Exception:
        pass
    if min_id:
        p2 = probe(
            "opendota /proMatches?less_than_match_id",
            f"{OPENDOTA}/proMatches?less_than_match_id={min_id}",
            "proMatches_p2.json",
            note=f"cursor={min_id}",
        )
        try:
            page2 = json.loads((AUDIT_DIR / "proMatches_p2.json").read_text())
            ids1 = {m["match_id"] for m in page}
            ids2 = {m["match_id"] for m in page2}
            p2["overlap_with_p1"] = len(ids1 & ids2)
            p2["max_id_p2"] = max(ids2)
        except Exception:
            pass

    # 3. Match detail for a recent pro match
    detail_keys = None
    if min_id:
        detail_id = page[0]["match_id"]
        d = probe(
            "opendota /matches/{match_id}",
            f"{OPENDOTA}/matches/{detail_id}",
            f"match_{detail_id}.json",
            note=f"match_id={detail_id}",
        )
        try:
            detail = json.loads((AUDIT_DIR / f"match_{detail_id}.json").read_text())
            detail_keys = sorted(detail.keys())
            d["player_keys"] = sorted(detail["players"][0].keys()) if detail.get("players") else None
            d["picks_bans_keys"] = (
                sorted(detail["picks_bans"][0].keys()) if detail.get("picks_bans") else None
            )
            d["has_series_fields"] = {k: detail.get(k) for k in ("series_id", "series_type", "leagueid", "patch")}
        except Exception:
            pass

    # 4-7. Reference endpoints
    probe("opendota /proPlayers", f"{OPENDOTA}/proPlayers", "proPlayers.json")
    probe("opendota /teams", f"{OPENDOTA}/teams", "teams.json")
    probe("opendota /leagues", f"{OPENDOTA}/leagues", "leagues.json")
    probe("opendota /heroStats", f"{OPENDOTA}/heroStats", "heroStats.json")

    # 8. Valve patch feed
    probe(
        "valve patchnoteslist",
        "https://www.dota2.com/datafeed/patchnoteslist?language=english",
        "valve_patchnoteslist.json",
    )

    # Report
    lines = ["# Phase 0 — Source Feasibility Audit", "", f"Generated by `scripts/phase0_audit.py`", ""]
    for r in results:
        lines.append(f"## {r['endpoint']}")
        lines.append(f"- URL: `{r['url']}`")
        lines.append(f"- Status: **{r.get('status', 'ERR')}** in {r.get('elapsed_s', '?')}s")
        if r.get("note"):
            lines.append(f"- Note: {r['note']}")
        if r.get("rate_limit_headers"):
            lines.append(f"- Rate-limit headers: `{r['rate_limit_headers']}`")
        if r.get("n_items") is not None:
            lines.append(f"- Items returned: {r['n_items']}")
        if r.get("item_keys"):
            lines.append(f"- Keys: `{', '.join(map(str, r['item_keys']))}`")
        if r.get("player_keys"):
            lines.append(f"- players[] keys ({len(r['player_keys'])}): `{', '.join(r['player_keys'])}`")
        if r.get("picks_bans_keys"):
            lines.append(f"- picks_bans[] keys: `{', '.join(r['picks_bans_keys'])}`")
        if r.get("has_series_fields"):
            lines.append(f"- Series/patch fields: `{r['has_series_fields']}`")
        if r.get("overlap_with_p1") is not None:
            lines.append(f"- Pagination overlap with page 1: {r['overlap_with_p1']} (expect 0)")
        if r.get("error"):
            lines.append(f"- ERROR: {r['error']}")
        lines.append("")

    (ROOT / "docs" / "phase0_audit.md").write_text("\n".join(lines), encoding="utf-8")
    (AUDIT_DIR / "audit_results.json").write_text(json.dumps(results, indent=2), encoding="utf-8")
    print(json.dumps(results, indent=2)[:6000])
    print(f"\nAudit written to docs/phase0_audit.md; samples in {AUDIT_DIR}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
